const TRANSLATIONS = {
	en: EN,
	vi: VI,
};

export type I18nKey = keyof typeof EN;
export type Translator = (key: I18nKey, params?: Record<string, string | number>) => string;

export function translate(
	language: TraderJournalLanguage,
	key: I18nKey,
	params: Record<string, string | number> = {},
): string {
	const template = TRANSLATIONS[language][key] ?? EN[key];
	return template.replace(/\{(\w+)\}/g, (match, paramName: string) => {
		const value = params[paramName];
		return value === undefined ? match : String(value);
	});
}

export function getTranslator(language: TraderJournalLanguage): Translator {
	return (key, params) => translate(language, key, params);
}

export function getLocale(language: TraderJournalLanguage): string | undefined {
	return language === 'vi' ? 'vi-VN' : undefined;
}

